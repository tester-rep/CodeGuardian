class TestMergerSeverityCap:
    """AI single-source findings must never reach CRITICAL; null_safety
    must not reach HIGH unless evidence shows actual dereference."""

    def test_ai_critical_capped_to_high(self):
        merger = ResultMerger(confidence_threshold=6)
        result = ReviewResult(
            chunk_file_path="a.py",
            findings=[
                AIFindingRaw(
                    title="Some Bug",
                    category="logic",
                    severity="critical",
                    confidence=8,
                    line_start=10, line_end=10,
                ),
            ],
            status="done",
        )
        output = merger.merge([result])
        assert len(output.primary) == 1
        assert output.primary[0].severity == Severity.HIGH

    def test_null_safety_high_without_dereference_evidence_capped_to_medium(self):
        merger = ResultMerger(confidence_threshold=6)
        result = ReviewResult(
            chunk_file_path="a.py",
            findings=[
                AIFindingRaw(
                    title="可能为 null",
                    category="null_safety",
                    severity="high",
                    confidence=7,
                    line_start=10, line_end=10,
                    evidence="变量 x 可能为 null",
                ),
            ],
            status="done",
        )
        output = merger.merge([result])
        assert len(output.primary) == 1
        assert output.primary[0].severity == Severity.MEDIUM

    def test_null_safety_high_with_npe_evidence_kept(self):
        merger = ResultMerger(confidence_threshold=6)
        result = ReviewResult(
            chunk_file_path="a.py",
            findings=[
                AIFindingRaw(
                    title="NPE 风险",
                    category="null_safety",
                    severity="high",
                    confidence=8,
                    line_start=10, line_end=10,
                    evidence="L10: x.method() 会触发 NullPointerException",
                ),
            ],
            status="done",
        )
        output = merger.merge([result])
        assert len(output.primary) == 1
        assert output.primary[0].severity == Severity.HIGH

    def test_confirmed_by_local_can_keep_high(self):
        """When local engine also finds the same issue, severity is preserved.
        The existing finding is upgraded in-place, not duplicated."""
        existing = Finding(
            id="SEC-001", title="SQL Injection", category="security",
            severity=Severity.HIGH, confidence=Confidence.MEDIUM,
            location=Location(file_path="a.py", line_start=10),
            source_engine="security",
        )
        merger = ResultMerger(confidence_threshold=6, existing_findings=[existing])
        result = ReviewResult(
            chunk_file_path="a.py",
            findings=[
                AIFindingRaw(
                    title="SQL Injection",
                    category="security",
                    severity="critical",  # AI says critical
                    confidence=9,
                    line_start=10, line_end=10,
                ),
            ],
            status="done",
        )
        output = merger.merge([result])
        # No new finding created — existing one upgraded in-place
        assert len(output.primary) == 0
        assert len(output.supplementary) == 0
        # Existing finding severity preserved (HIGH, not capped by AI single-source rule)
        assert existing.severity == Severity.HIGH
        assert existing.confidence == Confidence.HIGH
        assert "source:both" in existing.tags

