class TestReviewCacheTTL:
    """Tests for the cache TTL / expiration mechanism."""

    def _make_chunk(self, code: str = "x = 1") -> CodeChunk:
        return CodeChunk(
            file_path="test.py",
            source_code=code,
            language="python",
            line_start=1,
            line_end=1,
        )

    def _make_result(self, chunk: CodeChunk) -> ReviewResult:
        return ReviewResult(
            chunk_file_path=chunk.file_path,
            chunk_qualified_name=chunk.qualified_name,
            findings=[],
            summary="ok",
            status="done",
        )

    def test_store_and_lookup_within_ttl(self, tmp_path: Path):
        """Fresh entries should be retrievable."""
        from codeguardian.ai.deep_review.cache import ReviewCache

        cache = ReviewCache(tmp_path, ttl_seconds=3600)
        chunk = self._make_chunk()
        result = self._make_result(chunk)
        cache.store(chunk, result)

        hit = cache.lookup(chunk)
        assert hit is not None
        assert hit.status == "done"

    def test_expired_entry_returns_none(self, tmp_path: Path):
        """Entries older than TTL should be treated as cache miss."""
        import time as _time
        from codeguardian.ai.deep_review.cache import ReviewCache, _chunk_cache_key

        cache = ReviewCache(tmp_path, ttl_seconds=10)
        chunk = self._make_chunk()
        result = self._make_result(chunk)
        cache.store(chunk, result)

        # Manually backdate the _created_at timestamp
        key = _chunk_cache_key(chunk)
        cache._store[key]["_created_at"] = _time.time() - 20

        hit = cache.lookup(chunk)
        assert hit is None
        # Expired entry should have been removed from store
        assert key not in cache._store


