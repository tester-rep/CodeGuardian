def _make_finding(file_path: str, category: str, line: int = 10) -> Finding:
    """Helper: build a minimal Finding with the given category."""
    return Finding(
        id=f"X-{category}-{line}",
        title=f"{category} issue",
        category=category,
        severity=Severity.MEDIUM,
        confidence=Confidence.HIGH,
        location=Location(file_path=file_path, line_start=line, line_end=line),
        source_engine="test",
    )


def _make_chunk(file_path: str) -> CodeChunk:
    """Helper: build a minimal CodeChunk with default P2 priority."""
    return CodeChunk(
        file_path=file_path,
        source_code="def f():\n    pass\n",
        language="python",
        line_start=1,
        line_end=2,
        priority=2,
    )


def _make_pipeline_skeleton() -> DeepReviewPipeline:
    """Build a DeepReviewPipeline without running its heavy __init__.

    `_assign_priorities` does not touch any instance attribute, so an
    uninitialised skeleton is sufficient and avoids spinning up
    TreeSitterManager / parser caches in unit tests.
    """
    return object.__new__(DeepReviewPipeline)


def _make_ctx(tmp_path: Path) -> ScanContext:
    return ScanContext(project_root=str(tmp_path), config=load_app_config(None))


