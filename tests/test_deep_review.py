class TestTokenBudgetManager:
    def test_allocate_within_budget(self):
        budget = TokenBudgetManager(max_tokens=10000)
        chunks = [
            CodeChunk(file_path="a.py", source_code="x" * 400, language="python",
                      line_start=1, line_end=10, priority=0),
            CodeChunk(file_path="b.py", source_code="y" * 400, language="python",
                      line_start=1, line_end=10, priority=1),
        ]
        approved = budget.allocate(chunks)
        assert len(approved) == 2

    def test_allocate_exceeds_budget(self):
        budget = TokenBudgetManager(max_tokens=600)
        # Each chunk ~600 tokens, so only 1 should fit
        chunks = [
            CodeChunk(file_path="a.py", source_code="x" * 400, language="python",
                      line_start=1, line_end=10, priority=0),
            CodeChunk(file_path="b.py", source_code="y" * 400, language="python",
                      line_start=1, line_end=10, priority=1),
        ]
        approved = budget.allocate(chunks)
        assert len(approved) == 1

    def test_priority_ordering(self):
        budget = TokenBudgetManager(max_tokens=700)
        chunks = [
            CodeChunk(file_path="low.py", source_code="x" * 400, language="python",
                      line_start=1, line_end=10, priority=2),
            CodeChunk(file_path="high.py", source_code="y" * 400, language="python",
                      line_start=1, line_end=10, priority=0),
        ]
        approved = budget.allocate(chunks)
        assert len(approved) == 1
        assert approved[0].file_path == "high.py"  # P0 should be selected first

    def test_consume_tracks_spending(self):
        budget = TokenBudgetManager(max_tokens=1000)
        budget.consume(300)
        assert budget.spent == 300
        assert budget.remaining == 700

    def test_exhausted(self):
        budget = TokenBudgetManager(max_tokens=100)
        budget.consume(100)
        assert budget.exhausted is True


