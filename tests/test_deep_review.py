class TestLocalValidatorEvidenceSubstring:
    """LocalValidator.\\_check_evidence_substring must reject findings whose
    evidence quotes a token absent from the source code (hallucination).

    Regression: AI claimed line 264 had keyword 'retur' but the source
    actually contained 'return'. This check kills that entire failure mode.
    """

    def _make_validator(self, tmp_path: Path, file_rel: str, content: str):
        from codeguardian.ai.deep_review.local_validator import LocalValidator
        target = tmp_path / file_rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        return LocalValidator(tmp_path), file_rel

    def test_rejects_hallucinated_token_with_assertive_phrase(self, tmp_path):
        # Source has `return` on the flagged line; AI claims `retur` exists.
        source = "\n".join([
            "public class Foo {",                          # L1
            "    public int bar() {",                      # L2
            "        return 0;",                           # L3 ← target
            "    }",                                       # L4
            "}",                                           # L5
        ])
        validator, fp = self._make_validator(tmp_path, "Foo.java", source)
        finding = AIFindingRaw(
            title="语法错误",
            category="logic",  # whitelisted, would otherwise pass
            severity="critical",
            confidence=9,
            line_start=3, line_end=3,
            evidence="代码中存在关键字 'retur'，应该是 'return'",
        )
        kept, filtered = validator.filter_false_positives([finding], fp)
        assert kept == []
        assert filtered == [finding]

    def test_keeps_finding_when_token_actually_present(self, tmp_path):
        source = "\n".join([
            "public class Foo {",
            "    public int bar() {",
            "        return 0;",
            "    }",
            "}",
        ])
        validator, fp = self._make_validator(tmp_path, "Foo.java", source)
        # AI correctly references `return` which IS present.
        finding = AIFindingRaw(
            title="Real issue",
            category="logic",
            severity="medium",
            confidence=7,
            line_start=3, line_end=3,
            evidence="The 'return' statement should be wrapped in try/catch",
        )
        kept, filtered = validator.filter_false_positives([finding], fp)
        assert kept == [finding]
        assert filtered == []

    def test_no_assertive_phrase_no_substring_check(self, tmp_path):
        """Without assertive language, quoted tokens may legitimately
        reference symbols defined elsewhere — must not over-trigger."""
