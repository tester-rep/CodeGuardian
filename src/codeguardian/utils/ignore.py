"""Ignore patterns — determines which files/directories to skip during scanning.

Ensures only developer-written project code is analyzed:
  - Skips third-party deps, vendored code, system libraries
  - Parses .gitignore for project-specific exclusions
  - Detects generated code (protobuf, thrift, graphql, openapi, etc.)
  - Detects binary files early to avoid wasted parse time
  - Supports glob/fnmatch patterns for user exclude_paths
"""

